"""Exact (symbolic / rational) checks built on explicit 2x2 density matrices.

Three independent pieces:

1. ``witness_exact``      -- SymPy matrices with exact entries at eps = pi/3.
2. ``grouped_ceiling_exact`` -- exact unlimited-length grouped ceiling from the
   finite group generated by the gates (U_A^6 = -1, U_B^4 = -1).
3. ``universal_search``   -- a universal-in-eps decision procedure that differs
   from the repository certificate in every step: density matrices over the
   Gaussian rationals Q(i)[a, b] with a = cos(eps/2), b = sin(eps/2); D^2 as
   -det(rho_+ - rho_-); reduction to Q[t], t = cos(eps); factorisation into
   irreducibles; Sturm root *counting* with bisection (no simultaneous
   root isolation); exact rational sign evaluation.
"""
from __future__ import annotations

from fractions import Fraction
from itertools import product

import sympy as sp
from sympy import QQ, QQ_I
from sympy.polys.rings import ring

from .protocols import is_grouped

# ------------------------------------------------------------------ part 1 --


def _gates_sympy(eps, lam=1):
    """Kraus lists for A and B_{+-}; lam = exp(-gamma) (exact symbol or number)."""
    c, s = sp.cos(eps / 2), sp.sin(eps / 2)
    ua = sp.Matrix([[c, -s], [s, c]])
    p = (1 - lam) / sp.Integer(2)
    z = sp.diag(1, -1)
    out = {"B": {}}
    for h in (+1, -1):
        ub = sp.diag(sp.exp(-sp.I * h * sp.pi / 4), sp.exp(sp.I * h * sp.pi / 4))
        # Kraus operators sqrt(w) K stored as (w, K) so that no square roots
        # enter the arithmetic: rho -> sum_k w_k K_k rho K_k^dagger.
        out["B"][h] = [(1, ub)] if lam == 1 else [(1 - p, ub), (p, z * ub)]
    out["A"] = {h: [(1, ua)] for h in (+1, -1)}
    return out


def states_sympy(word, eps, lam=1):
    gates = _gates_sympy(eps, lam)
    res = []
    for h in (+1, -1):
        rho = sp.Matrix([[1, 0], [0, 0]])
        for name in word:
            rho = sum((w * k * rho * k.H for w, k in gates[name][h]), sp.zeros(2, 2))
            rho = rho.applyfunc(lambda e: sp.expand(sp.simplify(e)))
        res.append(rho)
    return res[0], res[1]


def witness_exact(word="ABABABAAB", eps=sp.pi / 3):
    plus, minus = states_sympy(word, eps)
    diff = (plus - minus).applyfunc(sp.nsimplify)
    d2 = sp.nsimplify(sp.simplify(-diff.det()))
    eig = sorted(diff.eigenvals().keys(), key=lambda v: float(v))
    return {
        "rho_plus": plus, "rho_minus": minus, "difference": diff,
        "D_squared": d2, "D": sp.sqrt(d2),
        "eigenvalues_of_difference": eig,
        "purity_plus": sp.simplify((plus * plus).trace()),
        "difference_over_sigma_y": sp.simplify(diff[1, 0] / sp.I),
    }


def witness_dephased_polynomial(word="ABABABAAB", eps=sp.pi / 3):
    """Exact D^2 as a polynomial in lam = exp(-gamma) (dephasing in each B)."""
    lam = sp.symbols("lambda", real=True)
    plus, minus = states_sympy(word, eps, lam)
    diff = plus - minus
    return lam, sp.factor(sp.expand(sp.simplify(-diff.det())))


# ------------------------------------------------------------------ part 2 --


def grouped_ceiling_exact(eps=sp.pi / 3):
    """Exact max D^2 over *all* grouped words of any length at this eps.

    Requires U_A^n = +-1 for some n (true for eps a rational multiple of pi);
    then rho depends on k mod n and m mod 4, so finitely many cases cover
    every grouped word A^k B^m and B^m A^k.
    """
    c, s = sp.cos(eps / 2), sp.sin(eps / 2)
    ua = sp.Matrix([[c, -s], [s, c]])
    period = None
    acc = sp.eye(2)
    for n in range(1, 200):
        acc = (acc * ua).applyfunc(sp.simplify)
        if acc == sp.eye(2) or acc == -sp.eye(2):
            period = n
            break
    if period is None:
        raise ValueError("U_A has no finite order up to 200")
    ub = sp.diag(sp.exp(-sp.I * sp.pi / 4), sp.exp(sp.I * sp.pi / 4))
    assert (ub ** 4).applyfunc(sp.simplify) == -sp.eye(2)
    best, arg = sp.Integer(0), ""
    for k in range(period):
        for m in range(4):
            for word in ("A" * k + "B" * m, "B" * m + "A" * k):
                plus, minus = states_sympy(word, eps)
                d2 = sp.nsimplify(sp.simplify(-(plus - minus).det()))
                if d2 > best:
                    best, arg = d2, word
    return {"A_period": period, "B_period": 4, "ceiling_D_squared": best, "argmax": arg}


# ------------------------------------------------------------------ part 3 --

_R, _a, _b = ring("a,b", QQ_I)
_I = QQ_I(0, 1)
_t = sp.symbols("t")


def _mm(x, y):
    return [[x[0][0] * y[0][0] + x[0][1] * y[1][0], x[0][0] * y[0][1] + x[0][1] * y[1][1]],
            [x[1][0] * y[0][0] + x[1][1] * y[1][0], x[1][0] * y[0][1] + x[1][1] * y[1][1]]]


_one, _zero = _R(1), _R(0)
_UA = [[_a, -_b], [_b, _a]]
_UAd = [[_a, _b], [-_b, _a]]
# sqrt(2) U_B(h) = diag(1 - i h, 1 + i h); the two sqrt(2) cancel into 1/2.
_UB = {h: [[_one - _I * h, _zero], [_zero, _one + _I * h]] for h in (1, -1)}
_UBd = {h: [[_one + _I * h, _zero], [_zero, _one - _I * h]] for h in (1, -1)}
_HALF = QQ_I(QQ(1, 2), 0)


def _step(rho, name, h):
    if name == "A":
        return _mm(_mm(_UA, rho), _UAd)
    m = _mm(_mm(_UB[h], rho), _UBd[h])
    return [[e * _HALF for e in row] for row in m]


def _to_t(poly_ab):
    """Reduce a polynomial in a=cos(eps/2), b=sin(eps/2) to Q[t], t=cos(eps).
    Raises if it is not real or not even in eps (a sin(eps) part survives)."""
    even, odd = sp.Integer(0), sp.Integer(0)
    for (p, q), coeff in poly_ab.terms():
        if coeff.y != 0:
            raise ArithmeticError("D^2 has a non-real coefficient")
        cval = sp.Rational(coeff.x.numerator, coeff.x.denominator)
        if p % 2 == 0 and q % 2 == 0:
            even += cval * ((1 + _t) / 2) ** (p // 2) * ((1 - _t) / 2) ** (q // 2)
        elif p % 2 == 1 and q % 2 == 1:
            odd += cval * ((1 + _t) / 2) ** (p // 2) * ((1 - _t) / 2) ** (q // 2) / 2
        else:
            raise ArithmeticError("mixed-parity monomial: not a function of eps")
    if sp.expand(odd) != 0:
        raise ArithmeticError("D^2 is not even in eps")
    return sp.Poly(sp.expand(even), _t, domain="QQ")


def distance_squared_polynomials(length):
    """{word: D^2 as Poly in t} for every word of exactly this length."""
    out = {}
    rho0 = [[_one, _zero], [_zero, _zero]]

    def rec(word, plus, minus):
        if len(word) == length:
            d00 = plus[0][0] - minus[0][0]
            d01 = plus[0][1] - minus[0][1]
            d10 = plus[1][0] - minus[1][0]
            out[word] = _to_t(d00 * d00 + d01 * d10)
            return
        for name in "AB":
            rec(word + name, _step(plus, name, 1), _step(minus, name, -1))

    rec("", rho0, rho0)
    return out


def _count_distinct_roots(factors, lo, hi):
    return sum(f.count_roots(lo, hi) for f in factors)


def strictly_feasible(candidate, competitors):
    """Is there t in (-1,1) with candidate(t) > g(t) for every competitor g?

    Returns (bool, rational sample or None).  Rigorous: the union of real
    roots of all differences is split by bisection into closed dyadic cells
    containing at most one distinct root each (Sturm counts on the distinct
    irreducible factors, which are pairwise coprime and squarefree).  Every
    open gap between consecutive roots then contains a cell endpoint, so
    testing all cell endpoints exactly decides feasibility of the open set.
    """
    diffs = [candidate - g for g in competitors]
    if any(d.is_zero for d in diffs):
        return False, None
    factors = set()
    for d in diffs:
        for f, _ in d.factor_list()[1]:
            factors.add(f.monic())
    factors = [f for f in factors if f.degree() > 0]
    cells = [(sp.Rational(-1), sp.Rational(1))]
    endpoints = set()
    while cells:
        lo, hi = cells.pop()
        if _count_distinct_roots(factors, lo, hi) <= 1:
            endpoints.update((lo, hi))
            continue
        mid = (lo + hi) / 2
        cells += [(lo, mid), (mid, hi)]
    for x in sorted(endpoints):
        if abs(x) == 1:
            continue
        if all(d.eval(x) > 0 for d in diffs):
            return True, x
    return False, None


def universal_search(max_len, verbose=False):
    """For each length L: unique D^2 polynomials, grouped competitors within
    budget L, and the words of length exactly L that strictly beat every
    grouped word of length <= L for some eps."""
    report = {}
    grouped_polys = set()
    for length in range(0, max_len + 1):
        polys = distance_squared_polynomials(length)
        grouped_polys |= {p for w, p in polys.items() if is_grouped(w)}
        comp = sorted(grouped_polys, key=lambda p: (p.degree(), str(p)))
        by_poly = {}
        for w, p in polys.items():
            by_poly.setdefault(p, []).append(w)
        witnesses, samples = [], {}
        for p, words in by_poly.items():
            if p in grouped_polys:
                continue  # identical to a grouped word: never strictly better
            ok, x = strictly_feasible(p, comp)
            if ok:
                witnesses += words
                for w in words:
                    samples[w] = str(x)
        report[length] = {
            "words": len(polys), "unique_D2_polynomials": len(by_poly),
            "grouped_competitors": len(comp),
            "witnesses": sorted(witnesses), "sample_t": samples,
        }
        if verbose:
            print(length, len(polys), len(by_poly), len(comp), sorted(witnesses), flush=True)
    return report
